#!/usr/bin/env python3
"""Generate Flutter/Dart and Compose/Kotlin icon-key adapters from icons.json.

Check mode is read-only and fails if generated adapters drift from the manifest.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path(__file__).with_name("icons.json")
DART = ROOT / "flutter/lib/src/generated_factory_icon_keys.dart"
KOTLIN = ROOT / "compose/src/main/kotlin/factory/icons/GeneratedFactoryIconKeys.kt"


def generate() -> tuple[str, str]:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    entries = manifest["icons"]
    ids = [item["id"] for item in entries]
    assert len(entries) == 24 and len(set(ids)) == 24
    assert ids == sorted(ids)
    assert all(x.replace("_", "").islower() and x.replace("_", "").isalpha()
               for x in ids)
    assert set(x["auto_mirror_rtl"] for x in entries) == {False, True}
    assert all(x["flutter"] and x["compose"] for x in entries)

    dart_cases = "\n".join(
        f"      FactoryIconKey.{x['id']} => Icons.{x['flutter']}," for x in entries
    )
    dart = (
        "// GENERATED by packs/icons/manifest/generate.py -- do not edit.\n"
        "import 'package:flutter/material.dart';\n\n"
        "/// Shared App Factory semantic icon identifiers.\n"
        "enum FactoryIconKey {\n"
        + "".join(f"  {x['id']},\n" for x in entries)
        + "}\n\n"
        "extension FactoryIconMapping on FactoryIconKey {\n"
        "  IconData get materialIcon => switch (this) {\n"
        f"{dart_cases}\n"
        "  };\n"
        "}\n"
    )

    kotlin_cases = "\n".join(
        f"    FactoryIconKey.{x['id'].upper()} -> "
        + ("Icons.AutoMirrored.Filled.ArrowBack" if x["auto_mirror_rtl"]
           else f"Icons.Filled.{x['compose']}")
        for x in entries
    )
    kotlin = (
        "// GENERATED by packs/icons/manifest/generate.py -- do not edit.\n"
        "package factory.icons\n\n"
        "import androidx.compose.material.icons.Icons\n"
        "import androidx.compose.material.icons.automirrored.filled.ArrowBack\n"
        "import androidx.compose.material.icons.filled.*\n"
        "import androidx.compose.ui.graphics.vector.ImageVector\n\n"
        "enum class FactoryIconKey {\n"
        + "".join(f"    {x['id'].upper()},\n" for x in entries)
        + "}\n\n"
        "fun FactoryIconKey.materialImageVector(): ImageVector = when (this) {\n"
        f"{kotlin_cases}\n"
        "}\n"
    )
    return dart, kotlin


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contents = generate()
    for path, expected in zip((DART, KOTLIN), contents):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Generated adapter is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    print("Icon generator PASS: 24 semantic keys, Flutter and Compose in sync")


if __name__ == "__main__":
    main()
